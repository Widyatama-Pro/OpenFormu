import type { Ingredient } from "../types";

type RuminantNutrientOverrides = Partial<Record<string, number | null>>;

function makeHartadiNutrients(overrides: RuminantNutrientOverrides): Ingredient["nutrients"] {
  const cp = overrides.cp ?? null;
  const cf = overrides.cf ?? null;
  const p = overrides.p ?? null;
  const lys = overrides.lys ?? null;

  const derivedSidLys =
    overrides.sid_lys !== undefined
      ? overrides.sid_lys
      : typeof lys === "number" && lys > 0
        ? Number((lys * 0.86).toFixed(3))
        : null;

  const avpRatio = cf === null || cf === 0 ? 0.95 : cf >= 18 ? 0.5 : 0.33;
  const derivedAvp =
    overrides.avp !== undefined
      ? overrides.avp
      : typeof p === "number" && p > 0
        ? Number((p * avpRatio).toFixed(3))
        : null;

  // Baseline elektrolit & sulfur (mg/kg BK) berdasarkan profil kelas bahan (Kearl 1982 Table 26 & NRC 1994 Table 9-1)
  const isForage = typeof cf === "number" && cf >= 18;
  const isProtein = typeof cp === "number" && cp >= 20 && !isForage;
  const hasOrganicProfile = cp !== null || cf !== null || overrides.tdn !== null;

  const derivedNa =
    overrides.na !== undefined
      ? overrides.na
      : hasOrganicProfile
        ? isForage
          ? 650
          : isProtein
            ? 850
            : 350
        : null;
  const derivedK =
    overrides.k !== undefined
      ? overrides.k
      : hasOrganicProfile
        ? isForage
          ? 16500
          : isProtein
            ? 14500
            : 4800
        : null;
  const derivedCl =
    overrides.cl !== undefined
      ? overrides.cl
      : hasOrganicProfile
        ? isForage
          ? 3800
          : isProtein
            ? 1200
            : 800
        : null;
  const derivedS =
    overrides.s !== undefined
      ? overrides.s
      : hasOrganicProfile
        ? typeof cp === "number" && cp > 0
          ? Math.round(cp * 110)
          : 1200
        : null;

  const derivedNdf =
    overrides.ndf !== undefined
      ? overrides.ndf
      : typeof cf === "number" && cf > 0
        ? Number(Math.min(88, cf * 1.95 + 4.5).toFixed(1))
        : cf === 0
          ? 0
          : null;
  const derivedAdf =
    overrides.adf !== undefined
      ? overrides.adf
      : typeof cf === "number" && cf > 0
        ? Number(Math.min(68, cf * 1.22 + 1.5).toFixed(1))
        : cf === 0
          ? 0
          : null;

  return {
    cp: null,
    me_poultry: null,
    tdn: null,
    ee: null,
    cf: null,
    ca: null,
    p: null,
    lys: null,
    met: null,
    metcys: null,
    thr: null,
    trp: null,
    val: null,
    sid_lys: derivedSidLys,
    avp: derivedAvp,
    na: derivedNa,
    k: derivedK,
    cl: derivedCl,
    s: derivedS,
    ndf: derivedNdf,
    adf: derivedAdf,
    starch: null,
    tannin: null,
    betn: null,
    liquid_fat: 0,
    ...overrides,
  };
}

